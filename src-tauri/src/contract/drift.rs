//! Contract drift test helper (docs/plan-features.md §2.1).
//!
//! Each contract module serializes one value per type into `src/ipc/contract/__fixtures__/<module>.ts`
//! as `export const name = <json> satisfies T.Type;`. `pnpm typecheck` then checks every fixture
//! against the TypeScript types (literal unions, missing and excess fields), and each value is
//! deserialized back here, so the TS shape is also what Rust accepts.
//!
//! The fixture files are committed. A test fails when its file differs from what the Rust types
//! produce; `UPDATE_FIXTURES=1 cargo test` rewrites them (a missing file is always written).
use std::path::PathBuf;

use serde::{Serialize, de::DeserializeOwned};

use crate::ipc::Json;

pub struct Fixtures {
    module: &'static str,
    entries: Vec<(String, String, Json)>,
}

impl Fixtures {
    pub fn new(module: &'static str) -> Self {
        Self { module, entries: Vec::new() }
    }

    /// One fixture value, typed as `ts_type` (a type exported from `src/ipc/types.ts`, `[]` allowed).
    /// Panics unless the value survives a JSON round trip unchanged.
    pub fn add<T: Serialize + DeserializeOwned>(&mut self, name: &str, ts_type: &str, value: &T) {
        let json = serde_json::to_value(value).expect("serialize fixture");
        let back: T = serde_json::from_value(json.clone()).unwrap_or_else(|e| panic!("{name}: does not deserialize: {e}"));
        let again = serde_json::to_value(&back).expect("serialize fixture");
        assert_eq!(json, again, "{name}: changes in a JSON round trip");
        self.entries.push((name.to_string(), ts_type.to_string(), json));
    }

    fn render(&self) -> String {
        let mut out = String::from(
            "// Generated by `cargo test` (src-tauri/src/contract/drift.rs) from the Rust contract types.\n\
             // Do not edit: `UPDATE_FIXTURES=1 cargo test` in src-tauri rewrites it. `pnpm typecheck` checks it.\n\
             import type * as T from \"../../types\";\n",
        );
        for (name, ty, json) in &self.entries {
            let body = serde_json::to_string_pretty(json).expect("pretty json");
            out.push_str(&format!("\nexport const {name} = {body} satisfies T.{ty};\n"));
        }
        out
    }

    /// Compares with (or writes) the committed fixture file.
    pub fn check(self) {
        let path: PathBuf = [env!("CARGO_MANIFEST_DIR"), "..", "src", "ipc", "contract", "__fixtures__"]
            .iter()
            .collect::<PathBuf>()
            .join(format!("{}.ts", self.module));
        let want = self.render();
        let have = std::fs::read_to_string(&path).ok().map(|s| s.replace("\r\n", "\n"));
        let update = std::env::var_os("UPDATE_FIXTURES").is_some_and(|v| v == "1");
        if have.is_none() || update {
            std::fs::create_dir_all(path.parent().expect("parent")).expect("fixture dir");
            std::fs::write(&path, &want).expect("write fixture");
            return;
        }
        assert!(
            have.as_deref() == Some(want.as_str()),
            "{} is out of date with the Rust contract types; run `UPDATE_FIXTURES=1 cargo test` and `pnpm typecheck`",
            path.display()
        );
    }
}
